#!/usr/bin/env bash
# brickOS prototype — mount ownership gate.
#
# The FS addon only registers a driver (br_fs_driver_register, fstype -> ops); the APP mounts by
# name with POSIX mount() and declares the plan in brick.toml [[mount]]. Breaking either fails
# silently, so:
#   ① br_mount_register must not appear in .c files under fs/** or driver/** (exemption: vfs-core's
#      own implementation and its conformance suite, which is what it tests);
#   ② no brick.toml outside app/** contains [[mount]];
#   ③ if app/ declares [[mount]], brickie must have generated an execution point (mount_plan_apply).
# Usage: bash tools/check-mount-ownership.sh; exit 0 pass, 1 violation, 2 environment error.
set -uo pipefail

cd "$(dirname "$0")/.." || exit 2

status=0
fail() { echo "FAIL: $*" >&2; status=1; }
pass() { echo "ok   $*"; }

# ---- ① FS addons (and the drivers) may not self-mount ----
hits="$(grep -rn --include='*.c' -E '\bbr_mount_register[[:space:]]*\(' fs driver 2>/dev/null || true)"
if [ -n "$hits" ]; then
    fail "FS addons/drivers still self-mount (should use br_fs_driver_register and let the APP mount):"
    printf '%s\n' "$hits" | sed 's/^/      /' >&2
else
    pass "nobody under fs/ or driver/ self-mounts (all register drivers instead)"
fi

# ---- ② [[mount]] belongs to the APP only ----
hits2="$(grep -rln --include='brick.toml' '^\[\[mount\]\]' . 2>/dev/null \
         | grep -v '^\./app/' | grep -v '^\./build/' || true)"
if [ -n "$hits2" ]; then
    fail "a non-APP brick.toml declares [[mount]] (the mount plan belongs to the consumer):"
    printf '%s\n' "$hits2" | sed 's/^/      /' >&2
else
    pass "[[mount]] appears only in the app/ declaration surface"
fi

# ---- ③ the APP side needs an execution point (a plan may not stop at the declaration) ----
if ! grep -rqn --include='brick.toml' '^\[\[mount\]\]' app 2>/dev/null; then
    echo "note: no [[mount]] declaration under app/ (legitimate: a product that mounts no FS)" >&2
else
    # only a generated "apply function" means it can really execute
    if grep -rqn 'mount_plan_apply' build/gen 2>/dev/null; then
        pass "the APP's mount plan was generated by brickie into an executable entry (mount_plan_apply)"
    else
        fail "app/ declares [[mount]] but mount_plan_apply was not generated -- the plan cannot execute (run brickie gen first)"
    fi
fi

if [ "$status" -eq 0 ]; then
    echo "PASS: mount ownership correct (FS registers drivers only / [[mount]] belongs to APP / plan has an execution entry point)"
fi
exit "$status"
