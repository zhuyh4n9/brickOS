#!/usr/bin/env bash
#
# brickOS prototype — the **mount ownership** gate (ADR-0030)
#
# Why it is needed:
#   ADR-0030 moves "who mounts" from **the FS addon itself** to **the APP**:
#     * the FS addon only registers a **driver** with vfs-core (`br_fs_driver_register`, fstype name → ops);
#     * the APP mounts by name with POSIX `mount(source, target, fstype, …)`, and the plan lives in
#       its own `brick.toml` under `[[mount]]`.
#
#   Both are the kind of rule where "**breaking it raises no error, behaviour just changes quietly**":
#     - if anyone writes one more `br_mount_register` into an FS addon, mounting becomes the FS's own
#       decision again -- and the functional tests **still mount fine**, so nobody notices;
#     - if anyone writes `[[mount]]` into an FS addon's brick.toml, the "mount plan" has two sources
#       of truth again (one in code, one in the manifest; see the repaid debt br-wa-fs-001).
#   ⇒ the criteria must be mechanical.
#
# Two criteria:
#   ① **FS may not self-mount**: `br_mount_register` must not appear in .c files under `fs/**` or `adapter/**`
#      (sole exemption: vfs-core's own implementation and its conformance suite -- that is exactly what it tests);
#   ② **`[[mount]]` belongs to the APP only**: no `brick.toml` outside `app/**` contains `[[mount]]`.
#
# Usage: bash tools/check-mount-ownership.sh
# Exit code: 0 = all pass, 1 = violation present, 2 = usage/environment error
set -uo pipefail

cd "$(dirname "$0")/.." || exit 2

status=0
fail() { echo "FAIL: $*" >&2; status=1; }
pass() { echo "ok   $*"; }

# ---- ① FS addons (and the adapter layer) may not self-mount -----------------------------------
# Exemption: framework/vfs-core -- `br_mount_register` is its own implementation, and its conformance
# suite uses it to build mount tables (that is exactly what it tests). Nobody else should call it directly.
hits="$(grep -rn --include='*.c' -E '\bbr_mount_register[[:space:]]*\(' fs adapter 2>/dev/null || true)"
if [ -n "$hits" ]; then
    fail "FS addons/adapter layer still self-mount (should use br_fs_driver_register and let the APP mount):"
    printf '%s\n' "$hits" | sed 's/^/      /' >&2
else
    pass "nobody under fs/ or adapter/ self-mounts (all register drivers instead)"
fi

# ---- ② [[mount]] belongs to the APP only ------------------------------------------------------
hits2="$(grep -rln --include='brick.toml' '^\[\[mount\]\]' . 2>/dev/null \
         | grep -v '^\./app/' | grep -v '^\./build/' || true)"
if [ -n "$hits2" ]; then
    fail "a non-APP brick.toml declares [[mount]] (the mount plan belongs to the consumer):"
    printf '%s\n' "$hits2" | sed 's/^/      /' >&2
else
    pass "[[mount]] appears only in the app/ declaration surface"
fi

# ---- ③ the APP side needs an execution point (positive criterion: a plan may not stop at the declaration) ----
if ! grep -rqn --include='brick.toml' '^\[\[mount\]\]' app 2>/dev/null; then
    echo "note: no [[mount]] declaration under app/ (legitimate: a product that mounts no FS)" >&2
else
    # only a generated "apply function" means it can really execute (see plan.rs for brickie's expansion point)
    if grep -rqn 'mount_plan_apply' build/gen 2>/dev/null; then
        pass "the APP's mount plan was generated by brickie into an executable entry (mount_plan_apply)"
    else
        fail "app/ declares [[mount]] but mount_plan_apply was not generated -- the plan cannot execute (run brickie gen first)"
    fi
fi

if [ "$status" -eq 0 ]; then
    echo "PASS: mount ownership correct (FS registers drivers only / [[mount]] belongs to APP / plan has an execution entry point)"
fi
exit "$status"
